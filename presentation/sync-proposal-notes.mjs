#!/usr/bin/env node
/* Regenerate the NOTES block in static/proposal.html from the deck's speaker notes.
 *
 *   NODE_PATH=$(npm root -g) node presentation/build-fleetmind-deck-v2.mjs   # notes live here
 *   node presentation/sync-proposal-notes.mjs                                # then run this
 *
 * proposal.html renders the speaker notes beside each slide. That block carried a
 * "由 pptx 的講者備忘稿產生，請勿手改" comment, but nothing generated it — it was hand-kept,
 * so editing addNotes() left the page showing the old script while the pptx carried the new
 * one. This makes the comment true.
 *
 * The pptx is the single source. k/t come from the slide (head() writes eyebrow then title as
 * its first two runs), cue/from/to are parsed from the note's leading [m:ss–m:ss], and n is the
 * note with that marker stripped.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PPTX = path.join(__dirname, "fleetmind-proposal-deck.pptx");
const HTML = path.join(__dirname, "..", "apps/api/src/main/resources/static/proposal.html");

// unzip via python (no dependency on a node zip lib).
// `uv run python3`, not bare `python3`: a wrapper on PATH rejects the latter.
const dump = execFileSync("uv", ["run", "python3", "-c", `
import zipfile, json, re, sys
from xml.sax.saxutils import unescape
z = zipfile.ZipFile(${JSON.stringify(PPTX)})

def dec(s):
    # raw <a:t> is XML-escaped: "DATA &amp; METHOD" must come back as "DATA & METHOD"
    return unescape(s, {'&quot;': '"', '&apos;': "'"})

def runs(name):
    """one entry per SHAPE, not per run: head() emits eyebrow and title as two addText
       calls = two <p:sp>, but a \\n inside a title splits it across <a:p> within one
       shape. Taking runs positionally truncated 'AI 船舶效能分析與\\n節能決策支援系統'
       to its first line."""
    if name not in z.namelist(): return []
    xml = z.read(name).decode('utf8')
    out = []
    for sp in re.findall(r'<p:sp>(.*?)</p:sp>', xml, re.S):
        t = ''.join(dec(x) for x in re.findall(r'<a:t>([^<]*)</a:t>', sp))
        if t.strip(): out.append(t)
    return out
def paras(name):
    """note text, one entry per <a:p>, so line breaks survive"""
    if name not in z.namelist(): return []
    xml = z.read(name).decode('utf8')
    out = []
    for p in re.findall(r'<a:p>(.*?)</a:p>', xml, re.S):
        out.append(''.join(dec(x) for x in re.findall(r'<a:t>([^<]*)</a:t>', p)))
    return out
n = sum(1 for x in z.namelist() if re.match(r'ppt/slides/slide\\d+\\.xml$', x))
data = []
for i in range(1, n+1):
    sr = runs(f'ppt/slides/slide{i}.xml')
    data.append({'i': i, 'slide': sr, 'notes': paras(f'ppt/notesSlides/notesSlide{i}.xml')})
print(json.dumps(data, ensure_ascii=False))
`], { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });

const slides = JSON.parse(dump);

const secs = (mmss) => { const [m, s] = mmss.split(":").map(Number); return m * 60 + s; };
const esc = (s) => JSON.stringify(s);

const entries = slides.map(({ i, slide, notes }) => {
  // notesSlide paragraphs end with the slide number pptxgenjs stamps in; drop it
  let body = notes.filter((p) => p.trim() !== String(i));
  const joined = body.join("\n").trim();

  // [0:00–0:30] on the first line, en-dash or hyphen
  const m = joined.match(/^\[(\d+:\d{2})\s*[–-]\s*(\d+:\d{2})\]\s*(.*)$/s);
  let cue = null, from = null, to = null, text = joined;
  if (m) {
    cue = `${m[1]}–${m[2]}`;
    from = secs(m[1]);
    to = secs(m[2]);
    text = m[3].trim();
  }
  const k = (slide[0] || "").trim();
  const t = (slide[1] || "").trim();
  const parts = [`k:${esc(k)}`, `t:${esc(t)}`];
  if (cue) parts.push(`cue:${esc(cue)}`, `from:${from}`, `to:${to}`);
  else parts.push(`cue:null`, `from:null`, `to:null`);
  parts.push(`n:${esc(text)}`);
  return `        {${parts.join(",")}},`;
});

const block = `      /* NOTES:BEGIN — generated by presentation/sync-proposal-notes.mjs from
         presentation/fleetmind-proposal-deck.pptx. Do not hand-edit: change addNotes() in
         build-fleetmind-deck-v2.mjs, rebuild the deck, then re-run the sync. */
var NOTES = [
${entries.join("\n")}
      ];      /* NOTES:END */`;

const html = fs.readFileSync(HTML, "utf8");
const re = /^ *\/\* NOTES:BEGIN[\s\S]*?\/\* NOTES:END \*\//m;
if (!re.test(html)) { console.error("NOTES block not found in proposal.html"); process.exit(1); }
fs.writeFileSync(HTML, html.replace(re, block));

const withCue = entries.filter((e) => !e.includes("cue:null")).length;
console.log(`synced ${entries.length} notes into proposal.html (${withCue} with timing cues, ${entries.length - withCue} without)`);
